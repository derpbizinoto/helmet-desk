using System;
using System.Collections.Generic;

namespace HelmetDesk.Core.Finance
{
    // Plain data saved inside data.json ("Finance"). All money is decimal, never double.
    // Amounts are always positive; the Kind says which way the money goes.

    public enum AccountType { Checking = 0, Wallet = 1, CreditCard = 2, Savings = 3 }
    public enum CategoryKind { Expense = 0, Income = 1 }
    public enum TxKind { Expense = 0, Income = 1, Transfer = 2 }

    public class Account
    {
        public string Id { get; set; } = NewId.Make();
        public string Name { get; set; } = "";
        public AccountType Type { get; set; }
        public decimal InitialBalance { get; set; }
        public string Color { get; set; } = "#8950D9";
        public string Icon { get; set; } = "";
        public bool Archived { get; set; }
        public DateTime CreatedAt { get; set; } = DateTime.Now;
    }

    public class Category
    {
        public string Id { get; set; } = NewId.Make();
        public string Name { get; set; } = "";
        public CategoryKind Kind { get; set; }
        public string Color { get; set; } = "#8950D9";
        public string Icon { get; set; } = "";
    }

    public class FinanceTransaction
    {
        public string Id { get; set; } = NewId.Make();
        public TxKind Kind { get; set; }
        public decimal Amount { get; set; }
        public DateTime Date { get; set; } = DateTime.Today;
        public string Description { get; set; } = "";
        public string? CategoryId { get; set; }
        public string? AccountId { get; set; }
        /// <summary>Transfers only: where the money goes.</summary>
        public string? ToAccountId { get; set; }
        public bool Paid { get; set; }
        public string Note { get; set; } = "";

        /// <summary>Generated by a recurrence: its id and the month ("yyyy-MM") it was generated for.</summary>
        public string? RecurrenceId { get; set; }
        public string? RecurrenceMonth { get; set; }

        /// <summary>Part of an installment purchase: the shared group id, this part's number (1-based) and the count.</summary>
        public string? InstallmentGroupId { get; set; }
        public int InstallmentNumber { get; set; }
        public int InstallmentCount { get; set; }

        /// <summary>Created by "Conferir saldo": changes the balance but is left out of income/expense totals and the chart.</summary>
        public bool IsAdjustment { get; set; }

        public DateTime CreatedAt { get; set; } = DateTime.Now;
        public DateTime UpdatedAt { get; set; } = DateTime.Now;

        public bool IsInstallment => InstallmentGroupId != null && InstallmentCount > 1;
        public bool IsRecurring => RecurrenceId != null;
    }

    /// <summary>A monthly model: generates one pending transaction per month when that month is opened.</summary>
    public class Recurrence
    {
        public string Id { get; set; } = NewId.Make();
        public TxKind Kind { get; set; }
        public string Description { get; set; } = "";
        public decimal Amount { get; set; }
        public string? CategoryId { get; set; }
        public string? AccountId { get; set; }
        public string? ToAccountId { get; set; }
        /// <summary>1–31; months without that day use their last day.</summary>
        public int DayOfMonth { get; set; } = 1;
        /// <summary>First month generated (day 1).</summary>
        public DateTime StartMonth { get; set; }
        /// <summary>Last month generated (day 1), or null for no end.</summary>
        public DateTime? EndMonth { get; set; }
        public bool Paused { get; set; }
        /// <summary>Months ("yyyy-MM") whose transaction was deleted on purpose: never generated again.</summary>
        public List<string> SkippedMonths { get; set; } = new();
    }

    public class FinanceData
    {
        public List<Account> Accounts { get; set; } = new();
        public List<Category> Categories { get; set; } = new();
        public List<FinanceTransaction> Transactions { get; set; } = new();
        public List<Recurrence> Recurrences { get; set; } = new();
        /// <summary>Default account of the next new transaction.</summary>
        public string? LastAccountId { get; set; }
        /// <summary>Default categories and the first account were created.</summary>
        public bool Seeded { get; set; }
    }

    internal static class NewId
    {
        public static string Make() => Guid.NewGuid().ToString("N");
    }
}
